CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(200) NOT NULL
    -- TODO LEARNER 2A: Add a table constraint that keeps member emails unique.
);

CREATE TABLE tools (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    category VARCHAR(80) NOT NULL,
    status VARCHAR(20) DEFAULT 'AVAILABLE' NOT NULL
    -- TODO LEARNER 2B: Constrain status to AVAILABLE, ON_LOAN, or MAINTENANCE.
);

CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    tool_id BIGINT NOT NULL,
    borrowed_on DATE NOT NULL,
    due_on DATE NOT NULL,
    returned_on DATE
    -- TODO LEARNER 2C: Add foreign keys to members and tools.
    -- TODO LEARNER 2D: Reject due dates before borrowed dates and return dates before borrowed dates.
);
